#!/usr/bin/env python3
"""Null fork: generate azalea-block/src/click_use.rs, the blocks that use a click.

A block "uses a click" when its class, or a superclass below Block, overrides
`useWithoutItem` or `useItemOn`. Vanilla then runs that action on a right-click, unless the
player crouches with an item in hand (MultiPlayerGameMode#performUseItemOn).

Usage (Python through uv):
    uv run codegen/gen_click_use_blocks.py <vanilla-src-dir> <version> > azalea-block/src/click_use.rs
where <vanilla-src-dir> holds the decompiled, Mojang-named sources (it has net/minecraft/...).
Example: uv run codegen/gen_click_use_blocks.py ~/Desktop/null-reference/vanilla-1.21.11-src 1.21.11
"""
import re
import sys
from pathlib import Path

src, version = Path(sys.argv[1]), sys.argv[2]
block_dir = src / "net/minecraft/world/level/block"

# class name -> (superclass, overrides a use method)
classes = {}
decl = re.compile(r"\b(?:class|interface)\s+(\w+)(?:<[^{]*?>)?\s*(?:extends\s+(\w+))?", re.S)
use = re.compile(r"\bInteractionResult\s+(?:useWithoutItem|useItemOn)\s*\(")
for f in block_dir.rglob("*.java"):
    text = f.read_text()
    m = re.search(r"\b(?:class|interface)\s+(\w+)(?:<[^{]*?>)?\s+extends\s+(\w+)", text, re.S)
    name = f.stem
    sup = m.group(2) if m and m.group(1) == name else None
    classes[name] = (sup, bool(use.search(text)))


def uses_click(cls):
    seen = set()
    while cls in classes and cls not in seen and cls not in ("Block", "BlockBehaviour"):
        seen.add(cls)
        sup, overrides = classes[cls]
        if overrides:
            return True
        cls = sup
    return False


# Registration helpers in Blocks.java that build a fixed class.
helper_class = {
    "registerBed": "BedBlock",
    "registerStainedGlass": "StainedGlassBlock",
    "registerStair": "StairBlock",
    "registerLegacyStair": "StairBlock",
}
blocks_text = (block_dir / "Blocks.java").read_text()
stmt = re.compile(r"public static final Block (\w+) = (\w+)\((.*?)\);\n", re.S)
registered = []  # (id, class)
for m in stmt.finditer(blocks_text):
    call, args = m.group(2), m.group(3)
    # the id is a string, or a constant of net.minecraft.references.Blocks (same name, upper case)
    ident = re.match(r'\s*(?:"(\w+)"|net\.minecraft\.references\.Blocks\.(\w+))', args)
    if not ident:
        continue
    block_id = ident.group(1) or ident.group(2).lower()
    if call in helper_class:
        cls = helper_class[call]
    elif call == "register":
        first = r'\s*(?:"\w+"|net\.minecraft\.references\.Blocks\.\w+)\s*,\s*'
        ref = re.match(first + r'(\w+)::new', args)
        lam = re.match(first + r'\w+\s*->\s*new\s+(\w+)', args, re.S)
        cls = ref.group(1) if ref else lam.group(1) if lam else "Block"
    else:
        continue
    registered.append((block_id, cls))

ids = sorted(i for i, c in registered if uses_click(c))
camel = lambda s: "".join(p.capitalize() for p in s.split("_"))
print(f"""// Generated by codegen/gen_click_use_blocks.py from the Minecraft {version} sources. Do not edit.
// Regenerate: uv run codegen/gen_click_use_blocks.py <vanilla-src-dir> {version} > azalea-block/src/click_use.rs
// Blocks whose class (or a superclass below Block) overrides useWithoutItem or useItemOn:
// {len(ids)} of {len(registered)} blocks.

use azalea_registry::builtin::BlockKind;

/// Whether a right-click on this block runs the block's own action (opens a screen, toggles,
/// and so on) instead of placing the held item. It is true for every block whose class
/// overrides a use method, even when a given state declines (an iron door), so it errs towards
/// asking for a crouch. A crouch with an item in hand skips that action and places the item
/// (vanilla `MultiPlayerGameMode#performUseItemOn`).
pub fn block_uses_click(kind: BlockKind) -> bool {{
    matches!(
        kind,""")
for i, n in enumerate(ids):
    print(f"        BlockKind::{camel(n)}{' |' if i < len(ids) - 1 else ''}")
print("    )\n}")
